package 김민규;

public class p52_RelationOperation 
{
	public static void main(String[] args)
	{
		int x = 3, y = 5;
		
		System.out.println(x < y);
		System.out.println(x > y);
		System.out.println(x <= y);
		System.out.println(x >= y);
		System.out.println(x ==y);
		System.out.println(x != y);
	}
}
